package org.geotools.jdbc;

import org.geotools.api.filter.FilterFactory;
import org.geotools.factory.CommonFactoryFinder;
import org.junit.Test;

import javax.print.DocFlavor;
import java.io.StringWriter;
import java.util.List;

import static org.junit.Assert.assertEquals;

public class PreparedFilterToSQLTest {

    FilterFactory ff = CommonFactoryFinder.getFilterFactory();

    @Test
    public void testIdAndClause() {
        var id = ff.id(ff.featureId("1"), ff.featureId("2"));
        var equals = ff.equals(ff.property("a"), ff.literal("0"));
        var and = ff.and(id, equals);
        var writer = new StringWriter();
        var filterToSql = new PreparedFilterToSQL(writer);
        filterToSql.setPrimaryKey(new PrimaryKey("test", List.of(new AutoGeneratedPrimaryKeyColumn("fid", String.class))));
        and.accept(filterToSql, null);
        System.out.println();
        assertEquals("((fid = ? OR fid = ?) AND a = ?)", writer.toString());
    }
}
